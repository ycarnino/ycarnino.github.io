// Regenerates ../js/map-data.js.
// Sources: world-atlas (Natural Earth, public domain) and us-atlas (US Census, public domain).
// Everything is projected once, here, to plain Web Mercator so the site needs no map library.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { presimplify, simplify, quantile } from "topojson-simplify";

const require = createRequire(import.meta.url);
const load = (p) => JSON.parse(readFileSync(require.resolve(p), "utf8"));

export const W = 3600; // world width in map units; 10 units = 1 degree of longitude
const project = ([lon, lat]) => {
  const phi = (Math.max(-58, Math.min(84, lat)) * Math.PI) / 180;
  return [((lon + 180) / 360) * W, W / 2 - (W / (2 * Math.PI)) * Math.log(Math.tan(Math.PI / 4 + phi / 2))];
};

const fmt = (n, dec) => {
  const s = n.toFixed(dec).replace(/\.?0+$/, "");
  return s === "-0" ? "0" : s;
};

function ringPath(ring, dec) {
  const k = 10 ** dec;
  const pts = [];
  // Rings that cross the antimeridian (Chukotka, the Aleutians, Fiji) are unwrapped to the east
  // so they do not smear a band across the whole map.
  const lons = ring.map((c) => c[0]);
  if (Math.max(...lons) - Math.min(...lons) > 180) ring = ring.map(([lon, lat]) => [lon < 0 ? lon + 360 : lon, lat]);
  for (const c of ring) {
    const [x, y] = project(c);
    const p = [Math.round(x * k) / k, Math.round(y * k) / k];
    const last = pts[pts.length - 1];
    if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
  }
  if (pts.length > 1 && pts[0][0] === pts.at(-1)[0] && pts[0][1] === pts.at(-1)[1]) pts.pop();
  if (pts.length < 3) return "";
  let d = `M${fmt(pts[0][0], dec)},${fmt(pts[0][1], dec)}l`;
  const seg = [];
  for (let i = 1; i < pts.length; i++) seg.push(`${fmt(pts[i][0] - pts[i - 1][0], dec)},${fmt(pts[i][1] - pts[i - 1][1], dec)}`);
  return d + seg.join(" ") + "z";
}

function geomPath(geom, dec) {
  if (!geom) return "";
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.type === "MultiPolygon" ? geom.coordinates : [];
  return polys.map((poly) => poly.map((r) => ringPath(r, dec)).join("")).join("");
}

function centroid(geom) {
  const polys = geom.type === "Polygon" ? [geom.coordinates] : geom.coordinates;
  let best = polys[0][0];
  for (const p of polys) if (p[0].length > best.length) best = p[0];
  let sx = 0, sy = 0;
  for (const c of best) { const [x, y] = project(c); sx += x; sy += y; }
  return [+(sx / best.length).toFixed(2), +(sy / best.length).toFixed(2)];
}

// --- World: 110m everywhere, 50m for the countries the Iberia view zooms into.
const DETAIL = new Set(["724", "620", "250", "020", "504"]); // Spain, Portugal, France, Andorra, Morocco
const w110 = load("world-atlas/countries-110m.json");
const w50 = load("world-atlas/countries-50m.json");
const countries = [];
for (const f of feature(w110, w110.objects.countries).features) {
  if (f.id === "010" || DETAIL.has(f.id)) continue; // drop Antarctica
  const d = geomPath(f.geometry, 1);
  if (d) countries.push([f.id ?? "", f.properties.name, d]);
}
for (const f of feature(w50, w50.objects.countries).features) {
  if (!DETAIL.has(f.id)) continue;
  countries.push([f.id, f.properties.name, geomPath(f.geometry, 2)]);
}

// --- US states (simplified a little; the 10m file is more detail than a phone needs).
let us = load("us-atlas/states-10m.json");
us = presimplify(us);
us = simplify(us, quantile(us, 0.35));
const states = feature(us, us.objects.states).features
  .filter((f) => Number(f.id) <= 56)
  .map((f) => [f.id, f.properties.name, geomPath(f.geometry, 2)]);

// --- Michigan counties, full detail, for the Ann Arbor / Saline view.
const co = load("us-atlas/counties-10m.json");
const counties = feature(co, co.objects.counties).features
  .filter((f) => String(f.id).startsWith("26"))
  .map((f) => [f.id, f.properties.name, geomPath(f.geometry, 3), ...centroid(f.geometry)]);

const out =
  "/* Generated by tools/build-map.mjs. Do not edit by hand. */\n" +
  "window.MAP_DATA=" + JSON.stringify({ W, countries, states, counties }) + ";\n";
writeFileSync(new URL("../js/map-data.js", import.meta.url), out);
console.log(`map-data.js ${(out.length / 1024).toFixed(0)} KB — ${countries.length} countries, ${states.length} states, ${counties.length} counties`);
